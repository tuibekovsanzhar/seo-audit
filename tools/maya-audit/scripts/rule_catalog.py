"""Write maya_audit/rule_ids.json from the finding-title frames in maya_audit_web/wording.py (DECISIONS 269).

The engine cannot import the web package, so the frames that already name every finding title (`wording.TITLES`) are
written out once as {check_id: [[rule_id, regex], ...]}. `tests/test_w12_rule_ids.py` fails when the file is stale.
Usage: python scripts/rule_catalog.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OUT = ROOT / "maya_audit" / "rule_ids.json"


def build() -> dict:
    from maya_audit_web import wording
    return {"_about": "Generated by scripts/rule_catalog.py from maya_audit_web/wording.py; do not edit by hand.",
            "rules": {check: [[key, pattern] for key, pattern in rows] for check, rows in sorted(wording.TITLES.items())}}


def main() -> None:
    OUT.write_text(json.dumps(build(), ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
