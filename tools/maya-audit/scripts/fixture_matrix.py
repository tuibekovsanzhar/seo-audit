"""Write docs/FIXTURE-MATRIX.md: which tests exercise each check, on broken, healthy and near-miss input.

Run: .venv/bin/python scripts/fixture_matrix.py          (tests/test_fixture_matrix.py fails when the file is stale)

How a test is classified. A test belongs to a check when the check's ID appears in the test's name or body.
It is counted as a "must not flag" test (a healthy site or a near miss) when its name says so: it contains
one of the words in QUIET. Every other test is counted as a "finds the problem" test. This reads names, not
intent, so it can miscount a test whose name does not say what it does; the gaps column is a prompt to look,
not a verdict.
"""
from __future__ import annotations

import ast
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUT = ROOT / "docs" / "FIXTURE-MATRIX.md"
CHECK_ID = re.compile(r"\b(?:INT|ACC|IDX|RND|STR|TSEO|PRF|ANS)-\d{1,2}\b")
QUIET = ("does_not", "do_not", "is_not", "are_not", "not_", "no_", "without", "leaves_out", "left_out", "passes", "_pass",
         "healthy", "clean", "unless", "but_not", "only_", "never", "nothing_to_say", "near_miss", "exempt", "skips", "ignored")
FAMILIES = ("INT", "ACC", "IDX", "RND", "STR", "TSEO", "PRF", "ANS")


def known_checks() -> list[str]:
    ids = [f"INT-{n}" for n in range(1, 5)] + [f"ACC-{n}" for n in range(1, 10)] + [f"IDX-{n}" for n in range(1, 11)]
    ids += [f"RND-{n}" for n in range(1, 8)] + [f"STR-{n}" for n in range(1, 24)] + ["TSEO-1"]
    return ids + [f"PRF-{n}" for n in range(1, 4)] + [f"ANS-{n}" for n in range(1, 6)]


def tests_by_check() -> dict[str, dict[str, list[str]]]:
    found: dict[str, dict[str, list[str]]] = defaultdict(lambda: {"finds": [], "quiet": []})
    known = set(known_checks())
    for path in sorted((ROOT / "tests").glob("test_*.py")):
        source = path.read_text(encoding="utf-8")
        for node in ast.walk(ast.parse(source)):
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
                text = node.name.upper().replace("_", "-") + "\n" + (ast.get_source_segment(source, node) or "")
                # "str16" in a name counts as STR-16.
                text = re.sub(r"\b(INT|ACC|IDX|RND|STR|TSEO|PRF|ANS)(\d{1,2})\b", r"\1-\2", text)
                kind = "quiet" if any(word in node.name for word in QUIET) else "finds"
                for check_id in sorted(set(CHECK_ID.findall(text)) & known):
                    found[check_id][kind].append(f"{path.name}::{node.name}")
    return found


def scenarios() -> dict[str, list[str]]:
    from fakeserver import SCENARIOS
    from fakeserver.acc_scenarios import ACC_SCENARIOS
    from fakeserver.idx_scenarios import IDX_SCENARIOS
    from fakeserver.prf_scenarios import PRF_SCENARIOS
    from fakeserver.rnd_scenarios import RND_SCENARIOS
    from fakeserver.str_scenarios import STR_SCENARIOS
    from fakeserver.ans_scenarios import ANS_SCENARIOS  # noqa: F401  (present in every build that has the ANS panel)

    return {"INT": sorted(SCENARIOS), "ACC": sorted(ACC_SCENARIOS), "IDX": sorted(IDX_SCENARIOS), "RND": sorted(RND_SCENARIOS),
            "STR / TSEO": sorted(STR_SCENARIOS), "PRF": sorted(PRF_SCENARIOS), "ANS": sorted(ANS_SCENARIOS)}


def render() -> str:
    found = tests_by_check()
    lines = ["# Fixture coverage matrix", "",
             "Generated by `scripts/fixture_matrix.py`; do not edit by hand. Every test here runs offline against the local",
             "fake server or an in-memory transport.", "",
             "A test belongs to a check when the check's ID is in the test's name or body. It is counted under **must not",
             "flag** (a healthy site or a near miss) when its name says so, otherwise under **finds the problem**. This reads",
             "names, not intent. **Gap** marks a check with no test on one side: a prompt to look, not proof of a hole.", "",
             "| Check | Finds the problem | Must not flag (healthy, near miss) | Gap |", "|---|---:|---:|---|"]
    gaps = []
    for check_id in known_checks():
        row = found.get(check_id, {"finds": [], "quiet": []})
        gap = "no test names this check" if not (row["finds"] or row["quiet"]) else \
            "no must-not-flag test by name" if not row["quiet"] else "no finds-the-problem test by name" if not row["finds"] else ""
        if gap:
            gaps.append(check_id)
        lines.append(f"| {check_id} | {len(row['finds'])} | {len(row['quiet'])} | {gap} |")
    lines += ["", f"Checks with a gap: {len(gaps)} of {len(known_checks())}" + (f" ({', '.join(gaps)})." if gaps else "."), "",
              "## Scripted sites (`fakeserver/`)", "",
              "Each is a small site built to show one situation. Tests run the real audit over them.", ""]
    for family, names in scenarios().items():
        lines.append(f"- **{family}** ({len(names)}): " + ", ".join(f"`{name}`" for name in names))
    lines += ["", "The web app's demonstration sites (`maya_audit_web/demo.py`) add a 500-page English and Turkish shop with planted",
              "problems and a 12-page Turkish site that audits clean; `tests/test_web_app.py` runs both.", "",
              "## Tests per check", ""]
    for check_id in known_checks():
        row = found.get(check_id, {"finds": [], "quiet": []})
        lines.append(f"### {check_id}")
        lines.append("")
        for label, names in (("Finds the problem", row["finds"]), ("Must not flag", row["quiet"])):
            lines.append(f"- {label}: " + (", ".join(f"`{name}`" for name in names) if names else "none by name"))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
