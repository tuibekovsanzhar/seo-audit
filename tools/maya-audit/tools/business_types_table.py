"""The business-type signals as a table for the team to review (DECISIONS 311): sector -> page type -> signals.

    .venv/bin/python tools/business_types_table.py [--seen docs/business-types/seen.json]

Writes docs/business-types/signals.md and docs/business-types/signals.xlsx from the profile files
(maya_audit/business_types/profiles/*.json). Every signal is marked:

- "tahmin" (guess): drafted by the agent, not yet seen matching a page on a saved audit. Review these first.
- "görüldü: <audits>" (seen): it matched pages on the saved audits listed in `seen.json` (written by
  tools/business_types_saved.py --seen). Seen is not the same as right: a match can still be a wrong page.
- "standart" for schema.org types: the type exists in schema.org; which page type it points to is still a guess
  unless seen.

Nothing is requested.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from maya_audit import business_types as bt  # noqa: E402
from maya_audit.xlsx import workbook  # noqa: E402

OUT = ROOT / "docs" / "business-types"
KINDS = (("url", "Adres sözcüğü", "url"), ("schema", "Yapısal veri türü", "schema"),
         ("words", "Başlık / menü sözcüğü", "heading"), ("content", "İçerik işareti", "content"))


def status(seen: dict, pid: str, tid: str, kind: str, value: str) -> str:
    kinds = ("heading", "menu") if kind == "heading" else (kind,)
    hits: dict[str, int] = {}
    for k in kinds:
        for audit, pages in (seen.get(f"{pid}|{tid}|{k}|{value}") or {}).items():
            hits[audit] = hits.get(audit, 0) + pages
    if hits:
        return "görüldü: " + ", ".join(f"{a} ({n} sayfa)" for a, n in sorted(hits.items()))
    return "tahmin (standart schema.org türü)" if kind == "schema" else "tahmin"


def rows(seen: dict) -> list[list]:
    out = []
    for pid, prof in bt.profiles().items():
        if pid == bt.DEFAULT:
            continue
        group = (bt.GROUPS.get(prof.get("group") or "") or {}).get("tr") or ""
        for t in prof["page_types"]:
            rank = t["rank"] if t["rank"] else "eklendi"
            for key, name, kind in KINDS:
                for value in (t.get("signals") or {}).get(key) or []:
                    out.append([prof["label"]["tr"], group, rank, t["label"]["tr"], t["weight"],
                                "evet" if t.get("citable") else "", name, value, status(seen, pid, t["id"], kind, value)])
            for g in t.get("generic") or []:
                out.append([prof["label"]["tr"], group, rank, t["label"]["tr"], t["weight"],
                            "evet" if t.get("citable") else "", "Genel sayfa türü (yedek)", g, "kural (Stage 3 türü)"])
    return out


HEADER = ["Sektör", "Grup", "Sıra", "Sayfa türü", "Ağırlık", "Alıntılanabilir", "İşaret türü", "İşaret", "Durum"]


def markdown(seen: dict) -> str:
    lines = ["# İşletme türleri: sayfa türü işaretleri (DECISIONS 311)", "",
             "Generated by `tools/business_types_table.py` from `maya_audit/business_types/profiles/*.json`; do not edit "
             "by hand. Source of the sectors and their order: `Maya-sektor-ve-oncelikli-sayfa-turleri.xlsx` (owner); "
             "\"Restoran / kafe\" and \"Diğer\": owner, 2026-11-05.", "",
             "**How a page gets a type.** Points per kind of signal, each kind once: address word "
             f"{bt.SCORES['url']}, structured-data type {bt.SCORES['schema']}, a word in the title or H1 "
             f"{bt.SCORES['heading']}, a word in the menu or link text pointing to the page {bt.SCORES['menu']}, a content "
             f"signal {bt.SCORES['content']}. A type needs {bt.MIN_SCORE}; ties go to the higher rank. Without a match the "
             "general page type (Stage 3) maps to the profile's type marked \"Genel sayfa türü\", else \"other\" "
             f"(weight {bt.UNMATCHED_WEIGHT}). The homepage, search/cart/account pages (0) and policy pages (15) are typed "
             "first. A structured-data type on half or more of the pages read is a site default and is ignored.", "",
             "**Address words:** `word` anywhere in a segment; `word/*` a folder with an item after it (a detail page); "
             "`word/` the last segment (the list page itself). Language folders (`/en/`) are skipped.", "",
             "**Weights:** by rank 100 / 85 / 70 / 55 / 40 / 30; the homepage is at least 85; \"eklendi\" = added by "
             "Stage 4 (the homepage where the sector list has none, at 85; \"Rehber / SSS / blog\" at 30, citable).", "",
             "**Durum** (what to review): **tahmin** = drafted, not yet seen matching a page on a saved audit; "
             "**görüldü** = it matched pages on the saved audits named (nihan, moodist, enpara, adile; offline, "
             "2026-11-05). Seen is not proof that the match is right.", "",
             "**Content signals:** " + "; ".join(f"`{k}` {v}" for k, v in bt.CONTENT_SIGNALS.items()) + ".", ""]
    table = rows(seen)
    current = None
    for row in table:
        sector = row[0]
        if sector != current:
            current = sector
            group = f" ({row[1]})" if row[1] else ""
            lines += ["", f"## {sector}{group}", "", "| Sıra | Sayfa türü | Ağırlık | İşaret türü | İşaret | Durum |",
                      "|---|---|---|---|---|---|"]
        cite = " · alıntılanabilir" if row[5] else ""
        lines.append(f"| {row[2]} | {row[3]}{cite} | {row[4]} | {row[6]} | `{row[7]}` | {row[8]} |")
    lines += ["", "## Önerinin işaretleri (Otomatik öner)", "",
              "Per profile: homepage structured data (+4), platform (+4), the share of the site's addresses with the "
              "profile's words (+4 at 10% or more, +3 at 3 addresses or 5%, else +1), the homepage menu's words (+1 each, "
              "at most 4). The best needs 4 and a lead of 1, else \"Diğer\" (\"Net bir işaret yok\").", "",
              "| Sektör | Ana sayfa yapısal verisi | Platform | Adres sözcükleri | Menü sözcükleri |", "|---|---|---|---|---|"]
    for pid, prof in bt.profiles().items():
        if pid == bt.DEFAULT:
            continue
        s = prof.get("suggest") or {}
        lines.append(f"| {prof['label']['tr']} | {', '.join(s.get('schema') or []) or '—'} | "
                     f"{', '.join(s.get('platforms') or []) or '—'} | {', '.join(s.get('url') or [])} | "
                     f"{', '.join(s.get('words') or [])} |")
    lines += ["", "All suggestion signals are guesses (tahmin) except where the four saved audits were suggested "
              "correctly: E-ticaret (nihan: Shopify, products/collections), Sağlık (moodist: Hospital markup, tedavi/"
              "doctors, menu), Bankacılık (enpara: kredi/mevduat addresses and menu), Restoran (adile: FoodEstablishment "
              "markup, sube/subeler).", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seen", default=str(OUT / "seen.json"))
    args = ap.parse_args(argv)
    seen_path = Path(args.seen)
    seen = json.loads(seen_path.read_text(encoding="utf-8")) if seen_path.is_file() else {}
    (OUT / "signals.md").write_text(markdown(seen), encoding="utf-8")
    table = rows(seen)
    sheets = [{"name": "İşaretler", "header": HEADER, "rows": table, "widths": [24, 8, 8, 30, 8, 12, 22, 26, 34]},
              {"name": "Gözden geçir (tahmin)", "header": HEADER, "rows": [r for r in table if r[8].startswith("tahmin")],
               "widths": [24, 8, 8, 30, 8, 12, 22, 26, 34]}]
    (OUT / "signals.xlsx").write_bytes(workbook(sheets))
    print(f"wrote {OUT / 'signals.md'} and {OUT / 'signals.xlsx'}: {len(table)} signals, "
          f"{sum(1 for r in table if r[8].startswith('tahmin'))} guesses")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
