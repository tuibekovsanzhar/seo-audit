def _load_locales() -> None:
    """Other languages are JSON files beside this one (locales/tr.json): the same keys as "en", translated values."""
    for path in sorted(LOCALES.glob("*.json")) if LOCALES.is_dir() else []:
        try:
            table = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if isinstance(table, dict) and path.stem != DEFAULT_LANGUAGE:
            STRINGS[path.stem] = {key: value for key, value in table.items() if isinstance(value, str) and key in STRINGS[DEFAULT_LANGUAGE]}


