def set_language(language: str | None) -> str:
    """Choose the language for what runs next in this request or worker. An unknown one means English."""
    chosen = language if language in STRINGS else DEFAULT_LANGUAGE
    _current.set(chosen)
    return chosen


def current_language() -> str:
    return _current.get()


def table(language: str | None = None) -> dict[str, str]:
    """Every sentence in one language; a sentence not translated yet is the English one."""
    chosen = language if language in STRINGS else DEFAULT_LANGUAGE
    return {**STRINGS[DEFAULT_LANGUAGE], **STRINGS[chosen]}


def has(key: str, language: str = DEFAULT_LANGUAGE) -> bool:
    return key in (STRINGS.get(language) or STRINGS[DEFAULT_LANGUAGE])


MISSING = "…"  # written where a sentence needs a value it was not given: never the braces of the template
_log = logging.getLogger(__name__)
_ANY_HOLE = re.compile(r"\{(\w+)(?:[:!][^{}]*)?\}")


def language_name(code: Any, language: str | None = None, /) -> Any:
    """A language code as its name in the reader's language ("en": "English", "İngilizce"). Anything that is not a
    known code comes back as it was given ("en-GB", a name already written out)."""
    key = f"language.{code.strip().lower()}" if isinstance(code, str) else None
    return t(key, language) if key and key != "language.label" and key in STRINGS[DEFAULT_LANGUAGE] else code


def t(key: str, language: str | None = None, /, **values) -> str:
    """The sentence for `key`, with its placeholders filled. An unknown key comes back as the key.

    `key` and `language` are given by position only, so a sentence may have a value named `language` or `key`
    (DECISIONS 169: "{headings} section headings are in {language}" was once printed as its raw template, because the
    value named `language` was taken for the interface language).

    A placeholder may carry the word for one and for many: `{count:page|pages}` gives "1 page" or "3 pages". Turkish
    does not change the noun after a number, so its sentences use the plain `{count}` (same placeholder names).

    A sentence is never returned with an unfilled hole. When a value is missing, the sentence's plain form
    (`<key>.plain`) is used if there is one; otherwise each missing value is written as "…" and a warning is logged."""
    chosen = STRINGS.get(language or _current.get()) or STRINGS[DEFAULT_LANGUAGE]
    template = chosen.get(key) or STRINGS[DEFAULT_LANGUAGE].get(key) or key
    try:
        return phrase(template, **values)
    except (KeyError, IndexError, ValueError):
        pass
    plain = None if key.endswith(".plain") else chosen.get(f"{key}.plain") or STRINGS[DEFAULT_LANGUAGE].get(f"{key}.plain")
    if plain:
        try:
            return phrase(plain, **values)
        except (KeyError, IndexError, ValueError):
            template = plain
    _log.warning("sentence %r was given no value for %s", key,
                 sorted({hole.group(1) for hole in _ANY_HOLE.finditer(template)} - set(values)) or "one of its holes")
    return _filled_anyway(template, values)


def _filled_anyway(template: str, values: dict[str, Any]) -> str:
    """`template` with every hole filled one at a time: a value that is missing, or does not fit its form, is "…"."""
    def one(hole: re.Match) -> str:
        if hole.group(1) not in values:
            return MISSING
        try:
            return phrase(hole.group(0), **values)
        except (KeyError, IndexError, ValueError):
            return str(values[hole.group(1)])
    return _ANY_HOLE.sub(one, template)


def usd(amount: float) -> str:
    """Money for a sentence: four decimals under ten cents (calls cost fractions of a cent), else two."""
    return f"{amount:.4f}" if 0 < abs(amount) < 0.1 else f"{amount:.2f}"
